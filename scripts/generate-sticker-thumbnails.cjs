const fs=require('node:fs'),path=require('node:path');
const sharp=require(process.env.SHARP_MODULE||'sharp');
(async()=>{
 const catalog={};let original=0,preview=0;
 for(const group of ['default','quiet-critters']){
  const dir=`assets/stickers/${group}`;
  for(const file of fs.readdirSync(dir).filter(f=>/\.(png|webp)$/i.test(f))){
   const source=`${dir}/${file}`,info=await sharp(source).metadata();
   if(Math.max(info.width,info.height)<=512||info.pages>1)continue;
   const target=`assets/stickers/thumbnails/${group}/${path.parse(file).name}.webp`;
   fs.mkdirSync(path.dirname(target),{recursive:true});
   await sharp(source).resize(192,192,{fit:'inside',withoutEnlargement:true}).webp({quality:90,alphaQuality:100}).toFile(target);
   catalog[source]=target;original+=fs.statSync(source).size;preview+=fs.statSync(target).size;
  }
 }
 fs.writeFileSync('shop/preview-images.js',`/* Generated by scripts/generate-sticker-thumbnails.cjs. Full-size placement sources are unchanged. */\nwindow.prepareShopPreviewImage=image=>{\n const previews=${JSON.stringify(catalog,null,2)};\n const source=image.getAttribute('src')||'',thumb=previews[source.split('?')[0]];\n image.loading='lazy';image.decoding='async';\n if(thumb){image.addEventListener('error',()=>{image.src=source},{once:true});image.src=thumb;}\n};\n`);
 console.log(`${Object.keys(catalog).length} thumbnails: ${original} original bytes, ${preview} thumbnail bytes`);
})();

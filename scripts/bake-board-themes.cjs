const fs=require('fs'),path=require('path'),sharp=require(process.env.SHARP_MODULE||'sharp');
(async()=>{
  const root=path.join(__dirname,'../assets/themes'),out=path.join(root,'baked');
  fs.mkdirSync(out,{recursive:true});
  const palette=fs.readFileSync(path.join(root,'palette.css'),'utf8');
  const names=[...new Set([...palette.matchAll(/assets\/themes\/([^"()]+\.svg)/g)].map(m=>m[1]))];
  for(const name of names){
    const cosmos=name.startsWith('cosmos-');
    if(process.argv.includes('--cosmos-only')&&!cosmos)continue;
    let svg=fs.readFileSync(path.join(root,name));
    const width=Number(svg.toString().match(/<svg\b[^>]*\bwidth="([\d.]+)"/)[1]);
    // Preserve native star detail across the 12,000 CSS pixel board.
    const target=cosmos?width:(name.includes('-board')?2560:1600);
    if(cosmos&&name.includes('-board')){
      // Render the shared nebula once rather than re-running its filters for
      // every rotated instance. The full-board stars are still rasterized natively.
      const source=svg.toString(),feature=source.match(/<g id="space-feature">([\s\S]*)<\/g><\/defs>/);
      const defs=source.slice(source.indexOf('<defs>')+6,source.indexOf('<g id="space-feature">'));
      const layer=await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="2400" height="1800" viewBox="-400 -400 2400 1800"><defs>${defs}</defs>${feature[1]}</svg>`)).png().toBuffer();
      svg=Buffer.from(source.replace(feature[0],`<g id="space-feature"><image x="-400" y="-400" width="2400" height="1800" href="data:image/png;base64,${layer.toString('base64')}"/></g></defs>`));
    }
    await sharp(svg,{density:72*target/width,limitInputPixels:100000000}).resize({width:target}).webp({quality:cosmos?98:88,effort:5}).toFile(path.join(out,name.replace('.svg','.webp')));
    console.log('Baked '+name+' at '+target+'px');
  }
  fs.writeFileSync(path.join(root,'baked.css'),palette.replace('Generated by scripts/generate-theme-artwork.cjs.','Generated by scripts/bake-board-themes.cjs from palette.css.').replace(/assets\/themes\/([^"()]+)\.svg/g,(_,name)=>'assets/themes/baked/'+name+'.webp'+(name.startsWith('cosmos-')?'?v=20260928-hd':'')));
})().catch(e=>{console.error(e);process.exitCode=1});
